#!/usr/bin/env python3
"""Independent numerical audit of the 93 ppn representative blocks.

This module intentionally does not import ``wick_reducer.reducer``.  It builds
the 93 blocks from the internal ppn slot action, evaluates every eight-term
block directly as an open six-Dirac-index tensor, and reports two different
notions of rank:

* fixed-axis rank: ordinary linear rank with output order ``ABCDEF``;
* view rank: representatives after allowing the two proton open-axis swaps
  ``A<->B`` and ``D<->E`` and a sign.

The second number is a contract-count audit.  A matched term is not an
ordinary fixed-axis linear combination: it is one already computed tensor
viewed with a recorded transpose and sign.  NumPy and opt_einsum are optional
runtime dependencies; the repository's symbolic enumerators remain standard
library only.
"""

from __future__ import annotations

from collections import Counter
import itertools
from pathlib import Path
import sys
from typing import Dict, Iterable, List, Mapping, Sequence, Tuple

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

try:
    import numpy as np
    import opt_einsum
except ImportError as exc:  # pragma: no cover - environment-dependent guard
    raise SystemExit(
        "This numerical audit needs numpy and opt_einsum; install them in the "
        "active Python environment before running the script."
    ) from exc

from kernels import correlator_wick_normalizer as core
from verify_code import ppn_orbit_contracts
from verify_code import ppnn_group_action as action
from kernels.wick_reducer import expression_output
from kernels.wick_reducer.operator_model import fields_for_operators, operator_library


def _blocks():
    """Rebuild the 93 canonical 8-term blocks from the ppn group action."""
    operators = operator_library()["ppn"]
    _fields, quarks, antiquarks = fields_for_operators(operators)
    terms = list(core.enumerate_wicks(quarks, antiquarks))
    if len(terms) != 2880:
        raise AssertionError(f"expected 2,880 raw Wicks, found {len(terms)}")
    wick_id_by_pairing = {
        term.pairing: index for index, term in enumerate(terms, start=1)
    }
    states = tuple(action.he3_states())
    state_wick_id = {
        state: wick_id_by_pairing[
            ppn_orbit_contracts._state_pairing(state, operators)
        ]
        for state in states
    }
    state_orbits = list(ppn_orbit_contracts._state_orbits(states))
    state_orbits.sort(key=lambda orbit: min(state_wick_id[state] for state in orbit))
    blocks = []
    for orbit in state_orbits:
        representative = min(orbit, key=lambda state: state_wick_id[state])
        pairings = ppn_orbit_contracts._state_pairings(representative, operators)
        blocks.append(tuple(sorted(wick_id_by_pairing[pairing] for pairing in pairings)))
    if len(blocks) != 93 or any(len(block) != 8 for block in blocks):
        raise AssertionError("expected 93 canonical blocks of eight Wicks")
    return operators, terms, blocks


def _random_inputs(seed: int) -> Dict[str, np.ndarray]:
    """Return generic perams and a scalar multiple of the 3D epsilon tensor."""
    rng = np.random.default_rng(seed)

    def random_complex(shape=()):
        return (
            rng.standard_normal(shape) + 1j * rng.standard_normal(shape)
        ) / np.sqrt(2.0)

    gamma = core._euclidean_gamma_matrices()
    epsilon = np.zeros((3, 3, 3), dtype=np.complex128)
    scalar = random_complex()
    for permutation in itertools.permutations(range(3)):
        inversions = sum(
            permutation[i] > permutation[j]
            for i in range(3)
            for j in range(i + 1, 3)
        )
        epsilon[permutation] = (-1 if inversions % 2 else 1) * scalar
    return {
        "C_g5": np.asarray(gamma["Cgamma5"], dtype=np.complex128),
        "C_g5_dagger": np.asarray(gamma["Cgamma5_dagger"], dtype=np.complex128),
        "peram_u_sin_sin": random_complex((3, 4, 3, 4)),
        "peram_u_sin_sou": random_complex((3, 4, 3, 4)),
        "peram_u_sou_sin": random_complex((3, 4, 3, 4)),
        "peram_u_sou_sou": random_complex((3, 4, 3, 4)),
        "VVV_sink": epsilon,
        "conj_VVV_source": epsilon.conjugate(),
    }


def _evaluate(
    operators, terms, wick_id: int, values: Mapping[str, np.ndarray]
) -> np.ndarray:
    term = terms[wick_id - 1]
    equation, operands, _output = expression_output.contraction_expression(
        operators, term.pairing, isospin_degenerate=True,
    )
    result = opt_einsum.contract(
        equation, *(values[name] for name in operands), optimize="greedy",
    )
    return term.sign * np.asarray(result, dtype=np.complex128)


def _axis_permutations() -> Tuple[Tuple[int, ...], ...]:
    """The four views generated by the two ppn proton open-axis swaps."""
    result = []
    for sink_swap in (False, True):
        for source_swap in (False, True):
            permutation = list(range(6))
            if sink_swap:
                permutation[0], permutation[1] = permutation[1], permutation[0]
            if source_swap:
                permutation[3], permutation[4] = permutation[4], permutation[3]
            result.append(tuple(permutation))
    return tuple(result)


def _view_classes(
    block: Sequence[int], vectors: Mapping[int, np.ndarray], tolerance: float,
) -> Tuple[int, List[Tuple[int, int, Tuple[int, ...], float]]]:
    """Find signed axis-view matches against deterministic earlier reps."""
    remaining = set(block)
    representatives = []
    matches = []
    for wick_id in sorted(block):
        if wick_id not in remaining:
            continue
        representatives.append(wick_id)
        remaining.remove(wick_id)
        for candidate in sorted(remaining):
            found = None
            for permutation in _axis_permutations():
                transformed = np.transpose(vectors[wick_id], permutation)
                scale = max(float(np.max(np.abs(vectors[candidate]))), 1.0)
                error = float(np.max(np.abs(vectors[candidate] - transformed)))
                if error <= tolerance * scale:
                    found = (1, permutation, error)
                    break
                error = float(np.max(np.abs(vectors[candidate] + transformed)))
                if error <= tolerance * scale:
                    found = (-1, permutation, error)
                    break
            if found is not None:
                remaining.remove(candidate)
                matches.append((candidate, wick_id, found[1], found[2] * found[0]))
    return len(representatives), matches


def audit(seeds: Iterable[int] = (1, 2, 3)) -> Dict[str, object]:
    operators, terms, blocks = _blocks()
    fixed_histograms = []
    view_histograms = []
    match_counts = []
    all_matches = []
    for seed in seeds:
        values = _random_inputs(int(seed))
        fixed_ranks = []
        view_ranks = []
        seed_matches = []
        for block_index, block in enumerate(blocks, start=1):
            vectors = {
                wick_id: _evaluate(operators, terms, wick_id, values)
                for wick_id in block
            }
            matrix = np.stack([vectors[wick_id].reshape(-1) for wick_id in block], axis=1)
            singular_values = np.linalg.svd(matrix, compute_uv=False)
            fixed_ranks.append(int(np.sum(singular_values > max(float(singular_values[0]), 1.0) * 1.0e-10)))
            view_rank, matches = _view_classes(block, vectors, tolerance=1.0e-8)
            view_ranks.append(view_rank)
            seed_matches.extend(
                (block_index, candidate, basis, sign, permutation, error)
                for candidate, basis, permutation, signed_error in matches
                for sign in (1 if signed_error >= 0 else -1,)
                for error in (abs(signed_error),)
            )
        fixed_histograms.append(dict(sorted(Counter(fixed_ranks).items())))
        view_histograms.append(dict(sorted(Counter(view_ranks).items())))
        match_counts.append(len(seed_matches))
        all_matches.append(seed_matches)
    if len(set(repr(item) for item in fixed_histograms)) != 1:
        raise AssertionError(f"fixed-axis rank changed across seeds: {fixed_histograms}")
    if len(set(repr(item) for item in view_histograms)) != 1:
        raise AssertionError(f"view rank changed across seeds: {view_histograms}")
    return {
        "canonical_blocks": len(blocks),
        "terms_per_block": 8,
        "candidate_contracts": len(blocks) * 8,
        "seeds": tuple(int(seed) for seed in seeds),
        "fixed_axis_rank_histogram": fixed_histograms[0],
        "fixed_axis_rank_sum": sum(k * v for k, v in fixed_histograms[0].items()),
        "axis_view_rank_histogram": view_histograms[0],
        "axis_view_rank_sum": sum(k * v for k, v in view_histograms[0].items()),
        "matched_view_count": match_counts[0],
        "view_matches_by_seed": match_counts,
        "view_matches": all_matches[0],
    }


def main() -> None:
    result = audit()
    for key, value in result.items():
        print(f"{key}: {value}")


if __name__ == "__main__":
    main()
